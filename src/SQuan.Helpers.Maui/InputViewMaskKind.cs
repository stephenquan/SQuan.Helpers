// InputViewMaskKind.cs

namespace SQuan.Helpers.Maui;

/// <summary>
/// An enumeration representing different kinds of input masks that can be applied to an InputView control.
/// </summary>
public enum InputViewMaskKind
{
	/// <summary>
	/// No input mask is applied.
	/// </summary>
	None,

	/// <summary>
	/// Numeric input mask is applied, allowing only numeric characters.
	/// </summary>
	Numeric,
};
